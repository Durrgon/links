"""Draw images/avatar-frame.svg: a runestone-style serpent band around the avatar.

A stone band circles the avatar with a runic inscription carved along it. It
starts as a tapering tail and ends in a serpent head, like the rune bands on
Viking-age runestones. Runes are drawn as lines, so no runic font is needed.

Usage: python scripts/make_avatar_frame.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "images" / "avatar-frame.svg"

SIZE = 200                 # viewBox is SIZE x SIZE, centred on (C, C)
C = SIZE / 2
R_OUT, R_IN = 97, 71       # band edges; the avatar shows inside R_IN
R_MID = (R_OUT + R_IN) / 2
BAND = R_OUT - R_IN
START, END = 118, 422      # band runs clockwise from START (tail) to END (head); 90 = bottom

INK = "#26262a"            # carved lines
STONE = "#cfcfca"          # stone colour before the grain
TEXT = "ᚾᚨᛏᛏᚠᛟᛞᛞ:ᛞᚱᚨᚲᛟᚾ:ᚾᚨᛏᛏᚠᛟᛞᛞ:ᛞᚱᚨᚲᛟᚾ"

# Elder Futhark letters as strokes in a 6 x 12 box (x right, y down); ":" is a word divider.
RUNES = {
    "ᚾ": "M3,0V12M1,4L5,7",
    "ᚨ": "M1,0V12M1,0L5,3M1,3L5,6",
    "ᛏ": "M3,0V12M0,3L3,0L6,3",
    "ᚠ": "M1,0V12M1,4L5,0M1,7L5,3",
    "ᛟ": "M3,0L6,4L0,12M3,0L0,4L6,12",
    "ᛞ": "M0,0V12M6,0V12M0,0L6,12M6,0L0,12",
    "ᚱ": "M1,12V0L5,3L1,6L5,12",
    "ᚲ": "M5,2L1,6L5,10",
}

# Serpent head at END, pointing clockwise (local +x); the band is y in [-13, 13], -y outward.
HEAD = ("M-3,-13 C6,-15 14,-17 23,-15 C31,-13 37,-9 41,-4 C44,-8 49,-7 49,-3 "
        "C49,1 45,3 41,3 C40,5 38,6 36,6 L26,7 C21,9 12,12 4,13 L-3,13")
HEAD_DETAIL = [
    "M40,1 C34,1 28,2 22,4",          # mouth
    "M2,-13 C4,-6 4,6 2,13",          # collar where the neck meets the band
    "M6,-13.5 C8,-6 8,6 6,13",
]
EYE = (25, -7)
# Tapering tail at START, pointing back (local -x).
TAIL = "M3,-13 C-8,-13 -20,-9 -28,-1 C-30,1 -29,3 -26,2 C-18,0 -8,6 3,13"


def polar(r, deg):
    a = math.radians(deg)
    return C + r * math.cos(a), C + r * math.sin(a)


def long_arc(r, a0, a1):
    """Clockwise arc from a0 to a1 degrees (may exceed 180), as two SVG arc commands."""
    mid = (a0 + a1) / 2
    (x0, y0), (xm, ym), (x1, y1) = polar(r, a0), polar(r, mid), polar(r, a1)
    return f"M{x0:.2f},{y0:.2f}A{r},{r} 0 0 1 {xm:.2f},{ym:.2f}A{r},{r} 0 0 1 {x1:.2f},{y1:.2f}"


def place(deg, r=R_MID):
    """Transform for local coords at angle deg: +x runs clockwise along the band, -y points outward."""
    x, y = polar(r, deg)
    return f"translate({x:.2f},{y:.2f}) rotate({deg + 90:.2f})"


def runes():
    first, last = START + 13, END - 15   # keep clear of the tail and head
    step = (last - first) / (len(TEXT) - 1)
    out = []
    for i, ch in enumerate(TEXT):
        t = place(first + i * step)
        if ch == ":":
            out.append(f'<g transform="{t}" fill="{INK}" stroke="none">'
                       f'<circle cy="-2.5" r="1.15"/><circle cy="2.5" r="1.15"/></g>')
        else:
            out.append(f'<path transform="{t} translate(-3,-6)" d="{RUNES[ch]}"/>')
    return "\n    ".join(out)


def svg():
    head, tail = place(END), place(START)
    band = long_arc(R_MID, START, END)
    edges = long_arc(R_OUT - 2.2, START, END) + " " + long_arc(R_IN + 2.2, START, END)
    details = "".join(f'<path d="{d}"/>' for d in HEAD_DETAIL)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}">
  <!-- Generated by scripts/make_avatar_frame.py: edit that, then rerun it. -->
  <defs>
    <filter id="stone" x="-5%" y="-5%" width="110%" height="110%">
      <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="3" seed="7" result="noise"/>
      <feColorMatrix in="noise" type="saturate" values="0" result="grey"/>
      <feComponentTransfer in="grey" result="grain">
        <feFuncR type="linear" slope="0.6" intercept="0.6"/>
        <feFuncG type="linear" slope="0.6" intercept="0.6"/>
        <feFuncB type="linear" slope="0.6" intercept="0.6"/>
        <feFuncA type="linear" slope="0" intercept="1"/>
      </feComponentTransfer>
      <feBlend in="SourceGraphic" in2="grain" mode="multiply" result="textured"/>
      <feComposite in="textured" in2="SourceGraphic" operator="in" result="stone"/>
      <feDropShadow in="stone" dx="0" dy="1.5" stdDeviation="1.6" flood-color="#000" flood-opacity="0.5"/>
    </filter>
  </defs>
  <g filter="url(#stone)" fill="{STONE}">
    <path d="{band}" fill="none" stroke="{STONE}" stroke-width="{BAND}"/>
    <path transform="{head}" d="{HEAD}Z"/>
    <path transform="{tail}" d="{TAIL}Z"/>
  </g>
  <g fill="none" stroke="{INK}" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">
    <path d="{edges}"/>
    <g transform="{head}"><path d="{HEAD}"/>{details}<circle cx="{EYE[0]}" cy="{EYE[1]}" r="2.6"/><circle cx="{EYE[0]}" cy="{EYE[1]}" r="0.8" fill="{INK}"/></g>
    <path transform="{tail}" d="{TAIL}"/>
    {runes()}
  </g>
</svg>
"""


if __name__ == "__main__":
    OUT.write_text(svg(), encoding="utf-8")
    print("Wrote", OUT)
